def country_blob(i, region):
    bloc = B.get(i, "nonaligned")
    ide = IDEO.get(i, "archive")
    name = NAME.get(i) or region["name"]
    if isinstance(name, list):
        name = name[0]
    capital = CAP.get(i, "узел не назван")
    official = OFF.get(i, name)
    pop = POP.get(i, "узел не публикует точную перепись")
    status = STATUS.get(i, BLOCS[bloc]["name"])
    relation = REL.get(i, REL_DEFAULT.get(bloc, "нейтральный обмен"))
    fact = FACT.get(i, "")
    if i in LONG:
        blurb = LONG[i]
    else:
        ide_name, ide_about = IDEOS[ide]
        blurb = (
            f"{name} в сентябре 2094-го держит стол в {capital}. {fact} "
            f"Идеология контура — {ide_name.lower()}: {ide_about} "
            f"С Гетьманатом отношения читаются так: {relation}."
        )
    return {
        "id": i,
        "name": name,
        "official": official,
        "capital": capital,
        "bloc": bloc,
        "ideology": ide,
        "pop": pop,
        "status": status,
        "relation": relation,
        "former": bool(region.get("former")),
        "flag": region.get("flag") or i,
        "blurb": blurb,
    }


